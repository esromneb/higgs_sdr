module pmi_fifo_dc #(
    parameter integer pmi_data_width_w = 8,
    parameter integer pmi_data_width_r = 8,
    parameter integer pmi_data_depth_w = 1024,
    parameter integer pmi_data_depth_r = 1024,
    parameter integer pmi_full_flag = 1024,
    parameter integer pmi_empty_flag = 0,
    parameter integer pmi_almost_full_flag = 1023,
    parameter integer pmi_almost_empty_flag = 1,
    parameter pmi_regmode = "noreg",
    parameter pmi_resetmode = "sync",
    parameter pmi_family = "ECP5U",
    parameter module_type = "pmi_fifo_dc",
    parameter pmi_implementation = "EBR"
) (
    input wire [pmi_data_width_w-1:0] Data,
    input wire WrClock,
    input wire RdClock,
    input wire Reset,
    input wire RPReset,
    input wire WrEn,
    output wire Full,
    input wire RdEn,
    output wire [pmi_data_width_r-1:0] Q,
    output wire Empty,
    output wire AlmostEmpty,
    output wire AlmostFull
);
    xpm_fifo_async #(
        .CDC_SYNC_STAGES(2),
        .DOUT_RESET_VALUE("0"),
        .ECC_MODE("no_ecc"),
        .FIFO_MEMORY_TYPE("auto"),
        .FIFO_READ_LATENCY(1),
        .FIFO_WRITE_DEPTH(pmi_data_depth_w),
        .FULL_RESET_VALUE(0),
        .PROG_EMPTY_THRESH(pmi_almost_empty_flag),
        .PROG_FULL_THRESH(pmi_almost_full_flag),
        .RD_DATA_COUNT_WIDTH($clog2(pmi_data_depth_r) + 1),
        .READ_DATA_WIDTH(pmi_data_width_r),
        .READ_MODE("std"),
        .RELATED_CLOCKS(0),
        .USE_ADV_FEATURES("1F1F"),
        .WAKEUP_TIME(0),
        .WR_DATA_COUNT_WIDTH($clog2(pmi_data_depth_w) + 1),
        .WRITE_DATA_WIDTH(pmi_data_width_w)
    ) fifo (
        .almost_empty(AlmostEmpty),
        .almost_full(AlmostFull),
        .data_valid(),
        .dbiterr(),
        .dout(Q),
        .empty(Empty),
        .full(Full),
        .overflow(),
        .prog_empty(),
        .prog_full(),
        .rd_data_count(),
        .rd_rst_busy(),
        .sbiterr(),
        .underflow(),
        .wr_ack(),
        .wr_data_count(),
        .wr_rst_busy(),
        .din(Data),
        .injectdbiterr(1'b0),
        .injectsbiterr(1'b0),
        .rd_clk(RdClock),
        .rd_en(RdEn),
        .rst(Reset | RPReset),
        .sleep(1'b0),
        .wr_clk(WrClock),
        .wr_en(WrEn)
    );
endmodule
